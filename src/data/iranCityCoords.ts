export function normalizePersianPlaceName(raw: string): string {
  return String(raw || '')
    .replace(/\(.*?\)/g, ' ')
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/آ/g, 'آ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function lookupLocalIranCoord(province: string, city: string): GeoCoord | null {
  const cleanCity = normalizePersianPlaceName(city);
  const cleanProv = normalizePersianPlaceName(province);

  if (cleanCity) {
    if (IRAN_CITY_COORDS[cleanCity]) {
      return IRAN_CITY_COORDS[cleanCity];
    }
    // Check substring matches like 'تهران / فیروزکوه'
    const cityKeys = Object.keys(IRAN_CITY_COORDS);
    const partial = cityKeys.find((k) => cleanCity.includes(k) || k.includes(cleanCity));
    if (partial) {
      return IRAN_CITY_COORDS[partial];
    }
  }

  if (cleanProv && IRAN_PROVINCE_CAPITALS[cleanProv]) {
    return IRAN_PROVINCE_CAPITALS[cleanProv];
  }

  return null;
}
