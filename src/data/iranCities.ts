export function getCitiesByProvince(provinceName: string): string[] {
  if (!provinceName) return IRAN_PROVINCES[0].cities;
  const match = IRAN_PROVINCES.find(
    (p) => p.name.trim() === provinceName.trim() || p.id === provinceName.toLowerCase().trim()
  );
  return match ? match.cities : [];
}

export function normalizeIranText(raw: string): string {
  return String(raw || '')
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/\u200c/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

export interface CitySearchMatch {
  province: string;
  city: string;
}

export function searchIranLocations(query: string, limit = 30): CitySearchMatch[] {
  const q = normalizeIranText(query);
  if (!q) return [];
  const exactStarts: CitySearchMatch[] = [];
  const subMatches: CitySearchMatch[] = [];
  const seen = new Set<string>();

  for (const prov of IRAN_PROVINCES) {
    const provNorm = normalizeIranText(prov.name);
    for (const c of prov.cities) {
      const cNorm = normalizeIranText(c);
      if (cNorm.includes(q) || provNorm.includes(q)) {
        const key = `${prov.name}::${c}`;
        if (!seen.has(key)) {
          seen.add(key);
          const item = { province: prov.name, city: c };
          if (cNorm.startsWith(q)) {
            exactStarts.push(item);
          } else {
            subMatches.push(item);
          }
        }
      }
    }
  }
  return [...exactStarts, ...subMatches].slice(0, limit);
}

export function parseProvinceCityText(rawText?: string | null): { province: string; city: string } | null {
  const raw = String(rawText || '').trim();
  if (!raw) return null;

  const parts = raw
    .split(/[/\-–—،,|]+/)
    .map((p) => p.replace(/^استان\s+|^شهرستان\s+|^شهر\s+/g, '').trim())
    .filter(Boolean);

  if (parts.length >= 2) {
    const firstNorm = normalizeIranText(parts[0]);
    const secondNorm = normalizeIranText(parts[1]);

    const firstProv = IRAN_PROVINCES.find(
      (p) => normalizeIranText(p.name) === firstNorm || firstNorm.includes(normalizeIranText(p.name))
    );
    if (firstProv) {
      return { province: firstProv.name, city: parts[1] };
    }

    const secondProv = IRAN_PROVINCES.find(
      (p) => normalizeIranText(p.name) === secondNorm || secondNorm.includes(normalizeIranText(p.name))
    );
    if (secondProv) {
      return { province: secondProv.name, city: parts[0] };
    }

    return { province: parts[0], city: parts[1] };
  }

  const singleNorm = normalizeIranText(raw);
  const provMatch = IRAN_PROVINCES.find(
    (p) => normalizeIranText(p.name) === singleNorm
  );
  if (provMatch) {
    return { province: provMatch.name, city: provMatch.cities[0] || provMatch.name };
  }

  for (const prov of IRAN_PROVINCES) {
    const cityMatch = prov.cities.find((c) => {
      const cNorm = normalizeIranText(c);
      return cNorm === singleNorm || singleNorm.includes(cNorm) || cNorm.includes(singleNorm);
    });
    if (cityMatch) {
      return { province: prov.name, city: cityMatch };
    }
  }

  const fuzzy = searchIranLocations(raw, 1);
  if (fuzzy.length > 0) {
    return { province: fuzzy[0].province, city: fuzzy[0].city };
  }

  return null;
}

export function resolveManagerProvinceCity(
  settings?: {
    managerProvince?: string;
    managerCity?: string;
    managerProvinceCity?: string;
    managerAddress?: string;
  } | null,
  fallbackUser?: { province?: string; city?: string } | null
): { province: string; city: string } {
  const directProv = (settings?.managerProvince || '').trim();
  const directCity = (settings?.managerCity || '').trim();
  if (directProv && directCity) {
    return { province: directProv, city: directCity };
  }

  const parsedFromField = parseProvinceCityText(settings?.managerProvinceCity);
  if (parsedFromField) {
    return {
      province: directProv || parsedFromField.province,
      city: directCity || parsedFromField.city,
    };
  }

  const parsedFromAddress = parseProvinceCityText(settings?.managerAddress);
  if (parsedFromAddress) {
    return {
      province: directProv || parsedFromAddress.province,
      city: directCity || parsedFromAddress.city,
    };
  }

  const fallbackParsed = parseProvinceCityText(fallbackUser?.city);
  if (fallbackUser?.province?.trim() && fallbackUser?.city?.trim()) {
    return {
      province: directProv || fallbackUser.province.trim(),
      city: directCity || fallbackUser.city.trim(),
    };
  }
  if (fallbackParsed) {
    return fallbackParsed;
  }

  return {
    province: directProv || 'تهران',
    city: directCity || 'فیروزکوه',
  };
}

